export async function seedCountries(prisma: PrismaClient): Promise<void> {
  // eslint-disable-next-line no-console
  console.log('🌍 Seeding countries...');

  for (const country of countriesData) {
    await prisma.countries.upsert({
      where: { code: country.code },
      update: {},
      create: {
        code: country.code,
        iso_code: country.iso_code,
        name: country.name,
        name_ar: country.name_ar,
        created_by: 'system',
        updated_by: 'system',
      },
    });
  }

  // eslint-disable-next-line no-console
  console.log(`✅ ${countriesData.length} countries seeded successfully!`);
}

// Main function to run seeding (only when executed directly)
async function main(): Promise<void> {
  const databaseUrl = process.env.DATABASE_URL;
  if (databaseUrl === undefined) {
    throw new Error('DATABASE_URL environment variable is required');
  }
  const adapter = new PrismaPg({
    connectionString: databaseUrl,
  });
  const prisma = new PrismaClient({ adapter });
  try {
    await seedCountries(prisma);
    // eslint-disable-next-line no-console
    console.log('✅ Countries seeding completed successfully!');
  } catch (error) {
    // eslint-disable-next-line no-console
    console.error('❌ Error in countries seeding:', error);
    throw error;
  } finally {
    await prisma.$disconnect();
  }
}

// Only run main if this file is executed directly
if (require.main === module) {
  main().catch((error) => {
    // eslint-disable-next-line no-console
    console.error(error);
    process.exit(1);
  });
}
